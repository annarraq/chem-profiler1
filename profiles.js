function getProfileKey(scores) {
  const theory = scores.theory - scores.practice >= 0 ? 'theory' : 'practice';
  const analysis = scores.analysis - scores.synthesis >= 0 ? 'analysis' : 'synthesis';
  const micro = scores.micro - scores.macro >= 0 ? 'micro' : 'macro';
  const careful = scores.careful - scores.risk >= 0 ? 'careful' : 'risk';
  return `${theory}-${analysis}-${micro}-${careful}`;
}

